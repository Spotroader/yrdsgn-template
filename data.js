window.YURU_parsePrice = s => parseFloat(String(s).replace(/\./g, "").replace(",", "."));
window.YURU_fmtPrice = n => Number(n).toLocaleString("tr-TR", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
window.YURU_installment = price => Math.round(window.YURU_parsePrice(price) / 12).toLocaleString("tr-TR");
window.YURU_stars = n => "★★★★★".slice(0, Math.round(n)) + "☆☆☆☆☆".slice(0, 5 - Math.round(n));
window.YURU_categoryUrl = slug => `category.html?cat=${slug}`;
window.YURU_collectionUrl = slug => `category.html?collection=${slug}`;
window.YURU_productUrl = id => `product.html?id=${id}`;
window.YURU_getProduct = id => window.YURU_CATALOG.products.find(p => p.id === String(id));
window.YURU_bestsellers = () => [...window.YURU_CATALOG.products]
  .sort((a, b) => (b.c || 0) - (a.c || 0) || (b.r || 0) - (a.r || 0))
  .slice(0, 8);
/** One product per category — hero preview rotation */
window.YURU_heroSlides = () => {
  const slides = [];
  const seen = new Set();
  for (const cat of window.YURU_CATALOG.categories) {
    const p = window.YURU_CATALOG.products.find(x => x.cat === cat.slug);
    if (p && !seen.has(p.id)) {
      seen.add(p.id);
      slides.push({
        id: p.id,
        img: cat.room || cat.image || p.img,
        name: p.name,
        badge: p.badge || "",
        cat: cat.name
      });
    }
  }
  return slides.length ? slides : window.YURU_CATALOG.products.slice(0, 8).map(p => {
    const cat = window.YURU_CATALOG.categories.find(c => c.slug === p.cat);
    return {
      id: p.id,
      img: cat?.room || cat?.image || p.img,
      name: p.name,
      badge: p.badge || "",
      cat: cat?.name || ""
    };
  });
};
